export function resolveGeometryMessages(
  translate?: ReachDeckTranslate,
): Readonly<Record<string, string>> {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(GEOMETRY_MESSAGE_DEFAULTS).map(([key, fallback]) => [
        key,
        translateReachDeck(translate, key, fallback),
      ]),
    ),
  );
}
